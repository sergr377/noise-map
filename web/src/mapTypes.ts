/**
 * Геометрия камеры и стиль — типы, не тянущие за собой сам движок карты.
 *
 * Свои типы, а не импорт значений из maplibre-gl: `usePanelMargin` меряет
 * панель, а `camera` считает метры на пиксель — обоим карта не нужна, и тянуть
 * ради двух кортежей саму библиотеку значило бы потерять то разделение, ради
 * которого они и вынесены в отдельные модули.
 */
import type { MapOptions } from 'maplibre-gl';

/**
 * Стиль подложки.
 *
 * Выведен из опций карты, а не импортирован из `@maplibre/maplibre-gl-style-spec`:
 * тот пакет попадает сюда транзитивно, и прямая ссылка на него сломалась бы от
 * смены его версии в недрах maplibre-gl. `string` отсекается намеренно — стиль
 * приезжает сюда уже загруженным объектом, см. `basemap.ts`.
 */
export type MapStyle = Exclude<NonNullable<MapOptions['style']>, string>;

/** Отступы в порядке CSS: сверху, справа, снизу, слева. */
export type Margin = [number, number, number, number];

/**
 * Рамка карты как `[[запад, север], [восток, юг]]`.
 *
 * Кортеж, а не `LngLatBounds`: `useComputedAreas` только раскладывает её на
 * четыре числа для запроса, и объект с методами пришлось бы разбирать там же —
 * а тип из библиотеки протёк бы в модуль, который к карте не обращается.
 */
export type Bounds = [[number, number], [number, number]];
